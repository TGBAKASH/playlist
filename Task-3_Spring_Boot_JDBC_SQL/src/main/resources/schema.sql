-- =========================================================
-- SQL Schema Definition for Harris Jayaraj Music Database
-- ANSI SQL Standard: Compatible with PostgreSQL (Neon) & H2
-- =========================================================

DROP TABLE IF EXISTS play_logs CASCADE;
DROP TABLE IF EXISTS favorites CASCADE;
DROP TABLE IF EXISTS songs CASCADE;

-- 1. Songs Table
CREATE TABLE songs (
    id INT PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    movie VARCHAR(100) NOT NULL,
    release_year VARCHAR(4) NOT NULL,
    duration VARCHAR(10) NOT NULL,
    query VARCHAR(150) NOT NULL,
    tags VARCHAR(100),
    play_count INT DEFAULT 0,
    is_favorite BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Favorites Table (Normalized Relational Table)
CREATE TABLE favorites (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_id INT NOT NULL,
    favorited_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_song_fav FOREIGN KEY (song_id) REFERENCES songs(id) ON DELETE CASCADE
);

-- 3. Play Activity Audit Logs
CREATE TABLE play_logs (
    log_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_id INT NOT NULL,
    played_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_song_log FOREIGN KEY (song_id) REFERENCES songs(id) ON DELETE CASCADE
);
